"""Transmit only locally built, hash-checked packages for this captured device.

Default is offline preflight. --execute --mode noop tests transfer/verification
with zero Flash erase/write ranges. Aligned restore/patch modes require saved
evidence and exact locally emulated packages. Unsafe legacy modes are excluded.
No general image/address API.
"""
import argparse, ctypes as C, datetime as dt, hashlib, json, struct, time
from ctypes import wintypes as W
from pathlib import Path
from mifi_wtp_probe import WinUsb, interfaces, api, check
from build_mifi_package import ROOT, OUT, BACKUP, BASELINE_SHA, PATCH_OFFSET, PATCH_SIZE, RECOVERY_OFFSET, RECOVERY_SIZE, ident

def sha(b): return hashlib.sha256(b).hexdigest()
def packet(cmd,payload=b'',seq=0): return struct.pack('<BBBBI',cmd,seq,0,0,len(payload))+payload

class Transport(WinUsb):
    expected=None
    def validate_packet(self,p):
        if p!=self.expected:raise ValueError('Packet not generated by bounded package flow')
        if p!=bytes.fromhex('00d3022b') and p[0] not in (0x20,0x26,0x27,0x2a,0x22,0x2b,0x30,0x31):
            raise ValueError('Excluded command')
    def raw(self,p,n=16384):
        self.expected=p
        try:return self.exchange(p,n)
        finally:self.expected=None
    def timeout(self,ms):
        f=api(C.WinDLL('winusb',use_last_error=True),'WinUsb_SetPipePolicy',W.BOOL,W.HANDLE,C.c_ubyte,W.ULONG,W.ULONG,C.c_void_p)
        val=W.ULONG(ms)
        for p in (self.pin,self.pout):check(f(self.usb,p,3,4,C.byref(val)),'Set transfer timeout')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--mode',choices=('noop','recover-original','apply-rate-off'),default='noop')
    ap.add_argument('--execute',action='store_true')
    ap.add_argument('--wait-seconds',type=int,default=180,choices=range(1,901))
    args=ap.parse_args()
    meta=json.loads((OUT/(args.mode+'.json')).read_text(encoding='utf8'))
    emu=json.loads((OUT/(args.mode+'-emulation.json')).read_text(encoding='utf8'))
    assert emu['completed'] and emu['entire_flash_model_matches_expected']
    assert sha(BACKUP.read_bytes())==BASELINE_SHA
    tim=(OUT/(args.mode+'.tim')).read_bytes()
    fbf=(OUT/(args.mode+'.fbf')).read_bytes()
    assert sha(tim)==meta['tim_sha256'] and sha(fbf)==meta['fbf_sha256']
    assert emu['fbf_sha256']==sha(fbf) and emu['tim_sha256']==sha(tim) and emu['backup_sha256']==BASELINE_SHA
    ranges=[] if args.mode=='noop' else [[RECOVERY_OFFSET,RECOVERY_SIZE]]
    assert meta['expected_write_ranges']==meta['expected_nonzero_erase_ranges']==ranges
    if args.mode!='noop':
        assert not meta.get('legacy_unaligned_unsafe')
        for block in (0x10000,0x20000):
            checked=json.loads((OUT/(args.mode+'-erase-'+hex(block)+'.json')).read_text(encoding='utf8'))
            assert checked['actual_erase_wrapper_executed'] and checked['entire_flash_model_matches_expected']
            assert checked['fbf_sha256']==sha(fbf) and checked['backup_sha256']==BASELINE_SHA
        image=next(x for x in meta['images'] if x['id']=='APCH')
        payload=fbf[image['offset']:image['offset']+image['length']]
        expected=bytearray(BACKUP.read_bytes()[RECOVERY_OFFSET:RECOVERY_OFFSET+RECOVERY_SIZE])
        if args.mode=='apply-rate-off':
            pos=PATCH_OFFSET-RECOVERY_OFFSET
            candidate='OSLO-rate-off.bin'
            expected[pos:pos+PATCH_SIZE]=(OUT/candidate).read_bytes()[0x237000:0x2c9000]
        assert payload==expected and len(payload)==RECOVERY_SIZE
    if not args.execute:
        print(json.dumps({'preflight':True,'mode':args.mode,'ranges':ranges,'fbf_sha256':sha(fbf)}));return
    # Local backup/profile and offline package checks are always required.
    # A first unlock also requires your own no-op transfer and readback proof.
    if args.mode=='apply-rate-off':
        assert any(json.loads(p.read_text(encoding='utf8')).get('transfer_completed') for p in Path('artifacts').glob('package-noop-*.json')), 'Complete a no-op transfer first'
        proof=json.loads(Path('artifacts/noop-readback-comparison.json').read_text(encoding='utf8'))
        assert proof['backup_sha256']==BASELINE_SHA and proof['original_firmware_matches'] and proof['identity_region_matches']
        decoder=json.loads((OUT/'rate-off-target-lzma.json').read_text(encoding='utf8'))
        assert decoder['passed'] and decoder['source_sha256']==sha((OUT/'OSLO-rate-off.bin').read_bytes()[0x237000:0x2c9000])
        assert not any(json.loads(p.read_text(encoding='utf8')).get('transfer_completed') for p in Path('artifacts').glob('package-apply-rate-off-*.json')), 'Already applied: read back before further work'
    report_backup_sha256=BASELINE_SHA
    report={'started_at_utc':dt.datetime.now(dt.timezone.utc).isoformat(),'mode':args.mode,
            'backup_sha256':report_backup_sha256,'expected_flash_ranges':ranges,'fbf_sha256':sha(fbf),'responses':[],'transfer_completed':False}
    dest=Path('artifacts')/('package-'+args.mode+'-'+dt.datetime.now(dt.timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'.json')
    usb=None
    try:
        print('Waiting for fresh boot port; mode',args.mode,flush=True)
        end=time.monotonic()+args.wait_seconds
        paths=interfaces()
        while not paths:
            if time.monotonic()>end:raise TimeoutError('No boot port')
            time.sleep(.05);paths=interfaces()
        assert len(paths)==1 and 'vid_2ecc&pid_3001' in paths[0].lower()
        usb=Transport(paths[0]);usb.timeout(10000)
        def send(cmd,data=b'',seq=0,allow_nack=False):
            raw=usb.raw(packet(cmd,data,seq))
            if len(raw)<6 or raw[0]!=cmd or raw[2]!=0 or len(raw)!=6+raw[5]:
                raise ValueError(('Unexpected response',cmd,seq,raw[:20].hex()))
            r={'cmd':cmd,'seq':raw[1],'status':raw[3],'flags':raw[4],'payload':raw[6:].hex()}
            if cmd not in (0x22,0x2a) or r['status']!=0:report['responses'].append(r)
            if raw[3]!=0 and not allow_nack:raise ValueError(('NACK',r))
            return r
        def drain(r,force=False,wait_ready=False):
            busy=wait_ready
            deadline=time.monotonic()+45
            for _ in range(450):
                if not force and not busy and not r['flags']&1:return
                if time.monotonic()>deadline:raise TimeoutError('Device remained busy')
                force=False
                r=send(0x2b,allow_nack=True)
                p=bytes.fromhex(r['payload'])
                if r['status']==0 and len(p)>=6 and p[0]==1:
                    raise ValueError(('Device error message',r))
                if r['status']==0 and len(p)>=6 and p[0]==0:
                    code=int.from_bytes(p[2:6],'little')
                    if code==1:busy=True
                    elif code==2:busy=False
                if r['status']!=0:
                    if not busy:return
                    time.sleep(.1)
            raise ValueError('Message queue not drained')
        def transfer(name,payload,selected=False):
            progress={'image':name,'total_bytes':len(payload),'confirmed_bytes':0,'done_sent':False,
                      'started_at_utc':dt.datetime.now(dt.timezone.utc).isoformat()}
            report['current_transfer']=progress
            dest.write_text(json.dumps(report,indent=2),encoding='utf8')
            if not selected:
                assert usb.raw(bytes.fromhex('00d3022b'))==bytes.fromhex('00d3022b')
                drain({'flags':1})
                r=send(0x20);assert r['payload']=='313133331420010633415a4e';drain(r)
                r=send(0x26);assert int.from_bytes(bytes.fromhex(r['payload']),'little')==ident(name);drain(r)
            drain(send(0x27,b'\0'))
            seq=0;offset=0
            while offset<len(payload):
                seq=(seq+1)&255
                r=send(0x2a,struct.pack('<I',len(payload)-offset),seq);drain(r)
                window=int.from_bytes(bytes.fromhex(r['payload']),'little')
                assert 0<window<=0x1000000 and not r['flags']&4
                window=min(window,len(payload)-offset)
                stop=offset+window
                while offset<stop:
                    chunk=payload[offset:min(offset+4096,stop)]
                    seq=(seq+1)&255
                    r=send(0x22,chunk,seq);drain(r)
                    offset+=len(chunk)
                    progress['confirmed_bytes']=offset
                if offset//1048576!=(offset-window)//1048576:
                    print(name,'transferred',offset,'/',len(payload),flush=True)
                    dest.write_text(json.dumps(report,indent=2),encoding='utf8')
            drain({'flags':1})
            progress['done_sent']=True
            dest.write_text(json.dumps(report,indent=2),encoding='utf8')
            drain(send(0x30),wait_ready=name=='FBFD')
            report.setdefault('images_completed',[]).append(name)
            dest.write_text(json.dumps(report,indent=2),encoding='utf8')
            print(name,'completed',len(payload),'bytes',flush=True)
        transfer('TIMH',tim)
        transfer('FBFD',fbf)
        transfer('OBMI',(ROOT/'OBMI.bin').read_bytes())
        report['transfer_completed']=True
        try:report['disconnect']=send(0x31)
        except OSError as exc:report['disconnect_error']=str(exc)
    except Exception as exc:
        report['error']=str(exc)
    finally:
        if usb:usb.close()
        report['finished_at_utc']=dt.datetime.now(dt.timezone.utc).isoformat()
        dest.write_text(json.dumps(report,indent=2),encoding='utf8')
        print('Report:',dest,'completed:',report['transfer_completed'],'error:',report.get('error'),flush=True)
    if not report['transfer_completed']:raise SystemExit(1)

if __name__=='__main__':main()
